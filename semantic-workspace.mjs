// Generate a disposable semantic index and an optional source-derived starting map.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { analyzeRepository } from './semantic-analysis.mjs';
import { applySemanticOverrides, buildSemanticView } from './semantic-views.mjs';

export async function buildSemanticWorkspace({root, out, title, authored = false}) {
  let index = await analyzeRepository(root);
  const overridesPath = path.join(root,'bitmap','semantics.json');
  try {
    const overrides = JSON.parse(await readFile(overridesPath,'utf8'));
    if (!overrides || typeof overrides !== 'object' || Array.isArray(overrides) || (overrides.version !== undefined && overrides.version !== 1)
      || (overrides.descriptions !== undefined && (!overrides.descriptions || typeof overrides.descriptions !== 'object' || Array.isArray(overrides.descriptions)
        || Object.values(overrides.descriptions).some(value=>typeof value !== 'string' || value.length > 4000)))) {
      throw Error('Use version 1 with a descriptions object containing text values of at most 4,000 characters.');
    }
    index = applySemanticOverrides(index,overrides);
    const ids = new Set(index.symbols.map(symbol=>symbol.id));
    const unmatched = Object.keys(overrides.descriptions ?? {}).filter(id=>!ids.has(id));
    if (unmatched.length) index.diagnostics.push(`${unmatched.length} curated descriptions did not match current symbol IDs. Check renamed or removed declarations.`);
  } catch (error) {
    if (error.code !== 'ENOENT') throw Error(`Cannot apply bitmap/semantics.json: ${error.message}`);
  }
  if (!authored && !index.symbols.length) throw Error('No supported JavaScript or TypeScript source was found. Supply --graph for another language or add supported source files.');
  await writeFile(path.join(out,'semantic.json'),JSON.stringify(index));
  if (authored) return index;
  const view = buildSemanticView(index);
  const git = (args, fallback) => {
    try { return execFileSync('git', args, {cwd:root,encoding:'utf8',stdio:['ignore','pipe','pipe'],env:{...process.env,GIT_OPTIONAL_LOCKS:'0'}}).trim(); }
    catch { return fallback; }
  };
  const workingTreeStatus = git(['status','--porcelain'],'unversioned');
  const metadata = {
    title,root,graph:view.graph,mermaid:view.mermaid,
    views:[{...view,id:'overview',label:'Source modules'},{...view,id:'all',label:'Source modules (focused)'}],
    builtAt:index.generatedAt,sourceCommit:git(['rev-parse','HEAD'],'uncommitted'),
    upstreamCommit:'7876ab0ca8b5ee46e836235e23c4886d5cdb79ae',
    workingTreeDirty:Boolean(workingTreeStatus),workingTreeStatus,
    reviewedFileHashes:Object.fromEntries(index.files.map(file=>[file.path,file.hash])),
    provenance:'Generated by static TypeScript/JavaScript analysis. Source symbols and supported relationships only; no runtime data flow inferred.',
    semanticGenerated:true,
    validation:{valid:true,checkedPaths:index.files.length,nodes:view.graph.nodes.length,edges:view.graph.edges.length},
  };
  await writeFile(path.join(out,'diagram.json'),JSON.stringify(metadata,null,2));
  for (const name of ['architecture','overview','all']) await writeFile(path.join(out,name+'.mmd'),view.mermaid);
  return index;
}
